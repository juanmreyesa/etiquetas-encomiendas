def available_languages():
    return [(code, LANG_NAMES.get(code, code)) for code in TRANSLATIONS]


def normalize_lang(lang):
    return lang if lang in TRANSLATIONS else DEFAULT_LANG


def t(key, lang=DEFAULT_LANG, **kw):
    """Traduce `key` al idioma `lang`, interpolando kwargs con str.format.
    Cae a español y, en última instancia, devuelve la propia key."""
    lang = normalize_lang(lang)
    s = TRANSLATIONS[lang].get(key)
    if s is None:
        s = TRANSLATIONS[DEFAULT_LANG].get(key, key)
    if kw:
        try:
            return s.format(**kw)
        except (KeyError, IndexError):
            return s
    return s
